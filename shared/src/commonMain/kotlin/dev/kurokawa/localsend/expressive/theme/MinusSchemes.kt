/** The Minus scheme for [id] ("pink", "blue_neutral", …), or null. */
internal fun minusColorScheme(id: String, dark: Boolean): ColorScheme? =
    when (id) {
        "pink" -> if (dark) PinkDarkScheme else PinkLightScheme
        "pink_neutral" -> if (dark) PinkNeutralDarkScheme else PinkNeutralLightScheme
        "red" -> if (dark) RedDarkScheme else RedLightScheme
        "red_neutral" -> if (dark) RedNeutralDarkScheme else RedNeutralLightScheme
        "blue" -> if (dark) BlueDarkScheme else BlueLightScheme
        "blue_neutral" -> if (dark) BlueNeutralDarkScheme else BlueNeutralLightScheme
        "orange" -> if (dark) OrangeDarkScheme else OrangeLightScheme
        "orange_neutral" -> if (dark) OrangeNeutralDarkScheme else OrangeNeutralLightScheme
        "yellow" -> if (dark) YellowDarkScheme else YellowLightScheme
        "yellow_neutral" -> if (dark) YellowNeutralDarkScheme else YellowNeutralLightScheme
        "aqua" -> if (dark) AquaDarkScheme else AquaLightScheme
        "aqua_neutral" -> if (dark) AquaNeutralDarkScheme else AquaNeutralLightScheme
        "cyan" -> if (dark) CyanDarkScheme else CyanLightScheme
        "cyan_neutral" -> if (dark) CyanNeutralDarkScheme else CyanNeutralLightScheme
        "purple" -> if (dark) PurpleDarkScheme else PurpleLightScheme
        "purple_neutral" -> if (dark) PurpleNeutralDarkScheme else PurpleNeutralLightScheme
        "green" -> if (dark) GreenDarkScheme else GreenLightScheme
        else -> null
    }
